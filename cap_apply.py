#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = [
#     "python-dotenv>=1.0",
# ]
# ///

"""Applies cap.config.json to Cap through its REST API.

Provision a new instance (or re-apply config to an existing one) from the Docker host,
where Cap's port 3000 is published and ADMIN_KEY is read from the .env next to this script:
    uv run cap_apply.py > cap-keys.env

Safe to re-run: sites are matched by name, created only when missing, and their config is merged on every run.
Instance sections left out of the config file are left alone; sections that are present replace what's there.

Site keys and secrets are generated by Cap, so every managed site's credentials are printed to stdout as env lines. Progress goes to stderr.
"""

import base64
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request

from dotenv import load_dotenv

INSTANCE_SECTIONS = ["headers", "ratelimit", "cors", "filtering"]
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def env_name(name):
    """Turns a site name into an env var prefix, e.g. "my-site" -> "CAP_MY_SITE"."""
    return "CAP_" + re.sub(r"^_|_$", "", re.sub(r"[^A-Z0-9]+", "_", name.upper()))


class CapClient:
    def __init__(self, base_url):
        self.base_url = base_url.rstrip("/")
        self.auth = None

    def request(self, method, path, body=None):
        headers = {}
        data = None
        if self.auth:
            headers["authorization"] = self.auth
        if body is not None:
            headers["content-type"] = "application/json"
            data = json.dumps(body).encode("utf-8")
        req = urllib.request.Request(
            self.base_url + path, data=data, headers=headers, method=method
        )
        try:
            with urllib.request.urlopen(req, timeout=30) as res:
                text = res.read().decode("utf-8")
        except urllib.error.HTTPError as e:
            text = e.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"{method} {path} -> {e.code}: {text}") from None
        return json.loads(text) if text else None

    def wait_until_healthy(self, timeout):
        """A freshly started instance may not be listening yet."""
        deadline = time.monotonic() + timeout
        while True:
            try:
                with urllib.request.urlopen(self.base_url + "/health", timeout=5):
                    return
            except (urllib.error.URLError, OSError) as e:
                if time.monotonic() >= deadline:
                    raise RuntimeError(
                        f"Cap at {self.base_url} not healthy after {timeout}s: {e}"
                    ) from None
                time.sleep(2)

    def login(self, admin_key):
        session = self.request("POST", "/auth/login", {"admin_key": admin_key})
        token = json.dumps(
            {"token": session["session_token"], "hash": session["hashed_token"]},
            separators=(",", ":"),
        )
        self.auth = "Bearer " + base64.b64encode(token.encode("utf-8")).decode("ascii")

    def logout(self):
        try:
            self.request("POST", "/server/logout", {})
        except Exception as e:  # never mask the real error
            print(f"logout failed: {e}")


def apply(client, config):
    instance = config.get("instance") or {}
    for section in INSTANCE_SECTIONS:
        if section not in instance:
            continue
        client.request("PUT", f"/server/settings/{section}", instance[section])
        print(f"instance: applied {section}")

    by_name = {}
    for key in client.request("GET", "/server/keys"):
        if key["name"] in by_name:
            raise RuntimeError(
                f'Two sites are named "{key["name"]}"; rename or delete one in the '
                "dashboard so the config can tell them apart"
            )
        by_name[key["name"]] = key

    sites = config.get("sites") or {}
    for name, site_config in sites.items():
        site_key = (by_name.get(name) or {}).get("siteKey")
        if not site_key:
            site_key = client.request("POST", "/server/keys", {"name": name})["siteKey"]
            print(f"site {name}: created {site_key}")
        client.request(
            "PUT", f"/server/keys/{site_key}/config", {**site_config, "name": name}
        )
        print(f"site {name}: applied config")

        secret_key = client.request("GET", f"/server/keys/{site_key}/secret")[
            "secretKey"
        ]
        print(f"{env_name(name)}_SITE_KEY={site_key}", flush=True)
        print(f"{env_name(name)}_SECRET_KEY={secret_key}", flush=True)

    for name in by_name:
        if name not in sites:
            print(f"site {name}: exists in Cap but not in the config, leaving it alone")


def main():
    # Variables already set in the environment take precedence over .env.
    load_dotenv(os.path.join(SCRIPT_DIR, ".env"))

    config_path = (
        sys.argv[1]
        if len(sys.argv) > 1
        else os.path.join(SCRIPT_DIR, "cap.config.json")
    )
    port = os.environ.get("SERVER_PORT") or "3000"
    cap_url = os.environ.get("CAP_URL") or f"http://127.0.0.1:{port}"
    admin_key = os.environ.get("ADMIN_KEY")
    if not admin_key:
        sys.exit("ADMIN_KEY is not set (environment or .env)")

    with open(config_path, encoding="utf-8") as f:
        config = json.load(f)

    client = CapClient(cap_url)
    client.wait_until_healthy(60)
    client.login(admin_key)
    try:
        apply(client, config)
    finally:
        client.logout()


if __name__ == "__main__":
    try:
        main()
    except RuntimeError as e:
        sys.exit(f"error: {e}")
